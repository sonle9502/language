
-- 1. Hồ sơ người dùng
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  created_at timestamptz not null default now()
);

-- 2. Đề thi
create table if not exists public.exams (
  id bigint generated by default as identity primary key,
  title text not null,
  level text not null check (level in ('N1','N2','N3','N4','N5')),
  description text,
  created_at timestamptz not null default now()
);

-- 3. Câu hỏi
create table if not exists public.questions (
  id bigint generated by default as identity primary key,
  exam_id bigint not null references public.exams(id) on delete cascade,
  question_text text not null,
  options jsonb not null default '[]'::jsonb,
  correct_answer text not null,
  explanation text,
  vocabulary text,
  vocabulary_meaning text,
  vocabulary_example text,
  sort_order int not null default 0
);

-- 4. Kết quả thi
create table if not exists public.exam_results (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  exam_id bigint not null references public.exams(id) on delete cascade,
  score int not null default 0,
  total_questions int not null default 0,
  answers jsonb not null default '{}'::jsonb,
  submitted_at timestamptz not null default now()
);

-- 5. Từ vựng yêu thích
create table if not exists public.favorite_vocabulary (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  word text not null,
  meaning text,
  example text,
  created_at timestamptz not null default now(),
  unique (user_id, word)
);

-- Bật RLS
alter table public.profiles enable row level security;
alter table public.exams enable row level security;
alter table public.questions enable row level security;
alter table public.exam_results enable row level security;
alter table public.favorite_vocabulary enable row level security;

-- Người dùng chỉ xem/sửa hồ sơ của mình
create policy "Read own profile"
on public.profiles for select
to authenticated
using (id = (select auth.uid()));

create policy "Insert own profile"
on public.profiles for insert
to authenticated
with check (id = (select auth.uid()));

create policy "Update own profile"
on public.profiles for update
to authenticated
using (id = (select auth.uid()))
with check (id = (select auth.uid()));

-- Người dùng đã đăng nhập được đọc đề thi và câu hỏi
create policy "Authenticated users read exams"
on public.exams for select
to authenticated using (true);

create policy "Authenticated users read questions"
on public.questions for select
to authenticated using (true);

-- Người dùng chỉ xem và quản lý kết quả của mình
create policy "Read own results"
on public.exam_results for select
to authenticated
using (user_id = (select auth.uid()));

create policy "Insert own results"
on public.exam_results for insert
to authenticated
with check (user_id = (select auth.uid()));

-- Người dùng chỉ quản lý từ vựng yêu thích của mình
create policy "Read own favorites"
on public.favorite_vocabulary for select
to authenticated
using (user_id = (select auth.uid()));

create policy "Insert own favorites"
on public.favorite_vocabulary for insert
to authenticated
with check (user_id = (select auth.uid()));

create policy "Delete own favorites"
on public.favorite_vocabulary for delete
to authenticated
using (user_id = (select auth.uid()));
